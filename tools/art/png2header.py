"""Convert the PNGs listed in art/manifest.json into C headers under include/art/.

Pixels are snapped to the nearest display color (art made by generate.py
already uses exact display colors). Alpha below 128 is transparent.
Run from the project root:  python3 tools/art/png2header.py
"""
import json
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from rgb332 import nearest  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ART = os.path.join(ROOT, "art")
OUT = os.path.join(ROOT, "include", "art")


def encode_row(row, opaque):
    """RLE: <0x80 = (n+1) literal pixels follow, >=0x80 = (n-0x7F) transparent."""
    out, x, w = [], 0, len(row)
    while x < w:
        start = x
        if not opaque[x]:
            while x < w and not opaque[x] and x - start < 128:
                x += 1
            out.append(0x7F + (x - start))
        else:
            while x < w and opaque[x] and x - start < 128:
                x += 1
            out.append(x - start - 1)
            out.extend(int(v) for v in row[start:x])
    return out


def convert(entry):
    img = Image.open(os.path.join(ART, entry["file"])).convert("RGBA")
    a = np.asarray(img)
    index = nearest(a[..., :3])
    opaque = a[..., 3] >= 128
    rows, data = [], []
    for y in range(img.height):
        rows.append(len(data))
        data.extend(encode_row(index[y], opaque[y]))
    ax, ay = entry.get("anchor", [0, 0])
    return img.width, img.height, ax, ay, rows, data


def c_array(values, per_line=24):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ",".join(str(v) for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    with open(os.path.join(ART, "manifest.json")) as f:
        manifest = json.load(f)
    os.makedirs(OUT, exist_ok=True)
    for group, entries in manifest.items():
        parts = [
            "#pragma once",
            "// Generated by tools/art/png2header.py from art/manifest.json. Do not edit;",
            "// change the PNGs in art/ and run the script again.",
            '#include "../GameGfx.h"',
            f"namespace {group} {{",
        ]
        total = 0
        for e in entries:
            w, h, ax, ay, rows, data = convert(e)
            total += len(data) + 4 * len(rows)
            n = e["name"]
            parts.append(f"const uint32_t {n}Rows[{len(rows)}] = {{\n{c_array(rows)}\n}};")
            parts.append(f"const uint8_t {n}Data[{len(data)}] = {{\n{c_array(data)}\n}};")
            parts.append(f"const GameGfx::Image {n} = {{{w}, {h}, {ax}, {ay}, {n}Rows, {n}Data}};")
        parts.append(f"}} // namespace {group}\n")
        path = os.path.join(OUT, f"{group}.h")
        with open(path, "w") as f:
            f.write("\n".join(parts))
        print(f"{group}: {len(entries)} images, {total / 1024:.1f} KB -> {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
